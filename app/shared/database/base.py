"""Declarative base, shared column types and mixins.

Type annotations drive column types, so `Mapped[Decimal]` is *always*
`NUMERIC(19, 4)` and `Mapped[datetime]` is *always* `TIMESTAMPTZ`. That makes
it impossible to accidentally introduce a FLOAT salary column.
"""

from __future__ import annotations

from datetime import date, datetime, time
from decimal import Decimal
from typing import Any, ClassVar
from uuid import UUID

from sqlalchemy import Date, DateTime, MetaData, Numeric, String, Time, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.ids import uuid7
from app.core.money import (
    PERCENTAGE_PRECISION,
    PERCENTAGE_SCALE,
    STORAGE_PRECISION,
    STORAGE_SCALE,
)

#: Deterministic constraint names keep Alembic autogenerate stable and make
#: `ALTER TABLE ... DROP CONSTRAINT` predictable across environments.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

MoneyNumeric = Numeric(STORAGE_PRECISION, STORAGE_SCALE, asdecimal=True)
PercentageNumeric = Numeric(PERCENTAGE_PRECISION, PERCENTAGE_SCALE, asdecimal=True)
#: Leave is counted in days with halves and quarters — two decimals is plenty,
#: and a narrower type than money keeps the two from being confused.
DaysNumeric = Numeric(9, 2, asdecimal=True)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Fetch server-generated values (created_at/updated_at, server defaults)
    # with RETURNING as part of the INSERT/UPDATE. Without this SQLAlchemy
    # leaves those attributes expired, and the first read of one from async
    # code would attempt blocking IO and raise MissingGreenlet.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 - SQLAlchemy API

    type_annotation_map: ClassVar[dict[Any, Any]] = {
        UUID: PGUUID(as_uuid=True),
        Decimal: MoneyNumeric,
        datetime: DateTime(timezone=True),
        date: Date(),
        time: Time(timezone=False),
        str: String(255),
        dict[str, Any]: JSONB,
    }

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        pk = getattr(self, "id", None)
        return f"<{type(self).__name__} id={pk}>"


class UUIDPrimaryKeyMixin:
    """UUIDv7 primary key generated by the application.

    Generating ids client-side lets us build a whole object graph (a payroll
    run plus every payslip plus every payslip item plus the outbox event)
    before touching the database, which keeps the payroll transaction to a
    small, bounded number of round-trips.
    """

    id: Mapped[UUID] = mapped_column(PGUUID(as_uuid=True), primary_key=True, default=uuid7)


class CreatedAtMixin:
    """For append-only tables, which have no meaningful `updated_at`."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False, index=True
    )


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class ActorTrackingMixin:
    """Who created and last changed the row.

    Deliberately *not* a foreign key with a cascade: deleting a user must
    never rewrite the history of the employee records they touched.
    """

    created_by: Mapped[UUID | None] = mapped_column(PGUUID(as_uuid=True))
    updated_by: Mapped[UUID | None] = mapped_column(PGUUID(as_uuid=True))


def money_column(**kwargs: Any) -> Mapped[Decimal]:
    """A NUMERIC(19,4) column defaulting to zero."""
    return mapped_column(
        MoneyNumeric,
        nullable=False,
        server_default=text("0"),
        default=Decimal("0.0000"),
        **kwargs,
    )


def days_column(**kwargs: Any) -> Mapped[Decimal]:
    """A NUMERIC(9,2) leave-day column defaulting to zero."""
    return mapped_column(
        DaysNumeric,
        nullable=False,
        server_default=text("0"),
        default=Decimal("0.00"),
        **kwargs,
    )
