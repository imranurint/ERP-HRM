"""Alembic environment.

Migrations run synchronously (psycopg) even though the application is async:
DDL is a deployment-time operation and a sync driver keeps the migration
runner simple and debuggable.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

from app.core.config import settings

# Importing the model registry populates Base.metadata for autogenerate.
from app.shared.database.models import Base

config = context.config
config.set_main_option("sqlalchemy.url", settings.sync_database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def _enum_check_constraint_names() -> frozenset[str]:
    """CHECK constraints generated by `Enum(native_enum=False)` columns.

    Autogenerate cannot round-trip these: it emits them on create but does not
    reflect them back into an `Enum` type, so every subsequent comparison
    reports them as "removed". They are real and present in the database —
    verify with `\\d+ employees` — so excluding them from comparison makes
    `alembic check` a usable drift signal instead of permanent noise.
    """
    from sqlalchemy import Enum

    names: set[str] = set()
    for table in target_metadata.tables.values():
        for column in table.columns:
            enum_type = column.type
            if isinstance(enum_type, Enum) and enum_type.name and not enum_type.native_enum:
                names.add(f"ck_{table.name}_{enum_type.name}")
    return frozenset(names)


#: Constraints and indexes created by raw SQL in the initial migration. They
#: have no declarative equivalent, so autogenerate would propose dropping them
#: on every run.
HAND_MANAGED_OBJECTS = frozenset(
    {
        "uq_employment_contracts_one_active",
        "ex_payroll_periods_no_overlap",
        "ex_employee_salary_structures_no_overlap",
        "ex_employee_shift_assignments_no_overlap",
        "ex_employee_leave_policies_no_overlap",
    }
)


def include_object(
    obj: object, name: str | None, type_: str, reflected: bool, compare_to: object
) -> bool:
    """Filter objects autogenerate is structurally unable to compare."""
    if name is None:
        return True
    return name not in HAND_MANAGED_OBJECTS


def include_name(name: str | None, type_: str, parent_names: dict[str, str | None]) -> bool:
    """Filter *reflected* names before they are compared.

    Check constraints are matched by name rather than by object, so the enum
    CHECK constraints have to be excluded here rather than in
    `include_object`.
    """
    if name is None:
        return True
    if type_ == "check_constraint" and name in _enum_check_constraint_names():
        return False
    return name not in HAND_MANAGED_OBJECTS


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting — for review or manual apply."""
    context.configure(
        url=settings.sync_database_url,
        target_metadata=target_metadata,
        include_object=include_object,
        include_name=include_name,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            include_object=include_object,
            include_name=include_name,
            compare_type=True,
            compare_server_default=True,
            # Keeps autogenerated constraint names identical to the models'.
            render_as_batch=False,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
